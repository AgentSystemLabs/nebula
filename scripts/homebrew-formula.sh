#!/bin/sh
# Print the Homebrew formula for one release, from its four tarballs.
#
#   scripts/homebrew-formula.sh 1.0.2 dist/ > Formula/orbit.rb
#
# The release workflow runs this after publishing, so Formula/orbit.rb on main
# always points at the latest release. The repo doubles as the tap:
#
#   brew install amenadem/orbit/orbit
#
# (`brew tap amenadem/orbit https://github.com/AmenAdem/Orbit` once first —
# the repo isn't named homebrew-orbit, so brew needs the URL spelled out.)
set -eu

version=${1:?usage: homebrew-formula.sh VERSION DIR}
dir=${2:?usage: homebrew-formula.sh VERSION DIR}
version=${version#v}
base="https://github.com/AmenAdem/Orbit/releases/download/v$version"

sha() {
    file="$dir/orbit-$1.tar.gz"
    [ -f "$file" ] || {
        echo "missing $file" >&2
        exit 1
    }
    shasum -a 256 "$file" | cut -d' ' -f1
}

# Up front, not inline in the heredoc: an `exit` inside `$(…)` only leaves
# the subshell, and the formula would go out with an empty sha256.
mac_arm=$(sha aarch64-apple-darwin)
mac_intel=$(sha x86_64-apple-darwin)
linux_arm=$(sha aarch64-unknown-linux-musl)
linux_intel=$(sha x86_64-unknown-linux-musl)

cat <<EOF
# Generated by scripts/homebrew-formula.sh — the release workflow rewrites it
# on every release, so edit the script rather than this file.
class Orbit < Formula
  desc "Mission control for your Claude Code sessions"
  homepage "https://github.com/AmenAdem/Orbit"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
      url "$base/orbit-aarch64-apple-darwin.tar.gz"
      sha256 "$mac_arm"
    end
    on_intel do
      url "$base/orbit-x86_64-apple-darwin.tar.gz"
      sha256 "$mac_intel"
    end
  end

  on_linux do
    on_arm do
      url "$base/orbit-aarch64-unknown-linux-musl.tar.gz"
      sha256 "$linux_arm"
    end
    on_intel do
      url "$base/orbit-x86_64-unknown-linux-musl.tar.gz"
      sha256 "$linux_intel"
    end
  end

  def install
    bin.install "orbit"
  end

  def caveats
    <<~TEXT
      After 'brew upgrade', a running orbit daemon stays on the old binary.
      Run 'orbit reload' to move it onto the new one (sessions keep running).
    TEXT
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/orbit --version")
  end
end
EOF
